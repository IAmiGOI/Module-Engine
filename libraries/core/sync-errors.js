/**
 * Ошибки синхронизации, после которых продолжать проход бессмысленно: провайдер сказал «места нет», «токен не годится» или «слишком много
 * запросов» — те же слова получит каждый следующий файл, и 400 одинаковых отказов только шумят и жгут лимиты. Исполнитель
 * ([sync-runner.js](sync-runner.js)) останавливает проход на первой такой ошибке, а не считает её ошибкой одного файла.
 *
 * Признак живёт флагом на объекте ошибки: такие ошибки рождаются и обрабатываются в одном процессе (сторона облака/GitHub → исполнитель),
 * через Шину контрактов и провод между устройствами они не ходят (там это была бы пометка в тексте, как `[deferred]`).
 */

export class FatalSyncError extends Error {
    constructor(message) { super(message); this.name = 'FatalSyncError'; this.fatal = true; }
}

export const isFatalError = error => error?.fatal === true;

/** Какие HTTP-статусы облака/GitHub означают «дальше бессмысленно»: вход, права/квота, лимит запросов, нет места. 404 сюда НЕ входит: один пропавший файл проход не останавливает. */
export const FATAL_HTTP_STATUSES = Object.freeze([401, 403, 429, 507]);
export const isFatalHttpStatus = status => FATAL_HTTP_STATUSES.includes(status);
