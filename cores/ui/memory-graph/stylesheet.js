/**
 * Стили Cytoscape окна графа памяти — MEMORY_GRAPH_UI_PLAN.md, Этап 1: чистый перенос массива `style: [...]` из
 * `ensureCytoscape()` (`cores/ui/memory-graph-panel.js`) БЕЗ ИЗМЕНЕНИЯ ПОВЕДЕНИЯ. Обёрнуто в функцию, а не голый
 * массив-константа — Этап 4 того же плана перепишет саму раскладку стилей (цвет по весу через `data(color)`,
 * размер через `data(size)`, свечение через `underlay-*`), и к тому моменту функции понадобятся параметры
 * (текущий режим карты и т.п.); сигнатура без аргументов сегодня — минимальная правка на этом этапе, не заявка на
 * будущий API.
 */

/** Идентификатор маркера места будущей ноды в режиме создания (см. `ensureCytoscape()`/`syncCytoscape()`) — вынесен сюда же, стиль ссылается на него через CSS-селектор `#id`. */
export const PREVIEW_ID = '__memory_graph_preview__';

export function graphStylesheet() {
    return [
        // Подпись СКРЫТА по умолчанию — при таком размере ноды текст
        // на весь холст был нечитаемым нагромождением (жалоба
        // пользователя). Показывается только классом `.hovered`,
        // который вешает/снимает `mouseover`/`mouseout` ниже.
        // Цвет — по важности (решено с пользователем: "чем важнее,
        // тем зеленее, чем менее важна, тем краснее"), линейная
        // интерполяция по шкале 0..10. Размер 2px→3px→7px (повторная
        // жалоба пользователя: "они все очень мелкие, увеличь размер"
        // — 3px оказалось всё ещё недостаточно на реальном масштабе
        // канваса).
        { selector: 'node', style: { 'background-color': 'mapData(importance, 0, 10, #e74c3c, #2ecc71)', color: '#fff', width: 7, height: 7 } },
        { selector: 'node.hovered', style: { label: 'data(label)', 'font-size': 0.9, 'text-valign': 'bottom', 'text-margin-y': 4 } },
        // Защищённые (центр/под-центр региона) — та же заливка по
        // важности, только БЕЛАЯ ОБВОДКА поверх отличает их роль,
        // не отдельный цвет заливки (иначе он бы спорил со шкалой
        // важности).
        { selector: 'node[?protectedNode]', style: { 'border-width': 1.5, 'border-color': '#fff' } },
        // Без подписи типа ребра — при реальном графе ("mentions"
        // почти на каждом ребре) текст сплошным нагромождением
        // покрывал весь холст (жалоба пользователя).
        { selector: 'edge', style: { width: 0.25, 'line-color': '#fff', 'curve-style': 'bezier' } },
        // Маркер места будущего узла в режиме создания — пунктир,
        // не сплошная заливка, чтобы не путать с настоящим узлом;
        // не кликабелен и не перетаскиваем (см. `grabbable`/`selectable` ниже).
        {
            selector: `#${PREVIEW_ID}`,
            style: {
                label: 'data(label)', 'background-color': 'rgba(74,158,255,0.15)',
                'border-width': 2, 'border-style': 'dashed', 'border-color': '#4a9eff',
                color: '#4a9eff', 'font-size': 9, 'text-valign': 'bottom', 'text-margin-y': 4,
                width: 2.4, height: 2.4,
            },
        },
    ];
}
